#!/usr/bin/env python3
"""Rasterize a TTF into an Adafruit/LovyanGFX GFXfont header."""

from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / "tools" / "fonts" / "Staatliches-Regular.ttf"
OUT = ROOT / "src" / "fonts" / "Scoreboard36pt7b.h"
SIZE = 36
FIRST = 0x20
LAST = 0x7E


def pack_bitmap(im: Image.Image) -> list[int]:
    pix = im.load()
    w, h = im.size
    bits: list[int] = []
    for y in range(h):
        for x in range(w):
            bits.append(1 if pix[x, y] else 0)
    out: list[int] = []
    acc = 0
    n = 0
    for b in bits:
        acc = (acc << 1) | b
        n += 1
        if n == 8:
            out.append(acc)
            acc = 0
            n = 0
    if n:
        out.append(acc << (8 - n))
    return out


def glyph_image(font: ImageFont.FreeTypeFont, ch: str, ascent: int, descent: int) -> tuple[Image.Image, int, int, int]:
    advance = max(1, int(round(font.getlength(ch))))
    if ch == " ":
        empty = Image.new("1", (0, 0), 0)
        return empty, advance, 0, 0
    pad = 4
    canvas_w = advance + pad * 2 + 8
    canvas_h = ascent + descent + pad * 2
    im = Image.new("1", (canvas_w, canvas_h), 0)
    draw = ImageDraw.Draw(im)
    origin = (pad, pad + ascent)
    draw.text(origin, ch, font=font, fill=1, anchor="ls")
    bbox = im.getbbox()
    if not bbox:
        empty = Image.new("1", (0, 0), 0)
        return empty, advance, 0, 0
    cropped = im.crop(bbox)
    x_off = bbox[0] - origin[0]
    y_off = bbox[1] - origin[1]
    return cropped, advance, x_off, y_off


def main() -> None:
    font = ImageFont.truetype(str(TTF), SIZE)
    ascent, descent = font.getmetrics()
    y_advance = ascent + descent + 2

    bitmaps: list[int] = []
    glyphs: list[tuple[int, int, int, int, int, int, str]] = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        im, advance, x_off, y_off = glyph_image(font, ch, ascent, descent)
        offset = len(bitmaps)
        packed = pack_bitmap(im) if im.size[0] and im.size[1] else []
        bitmaps.extend(packed)
        w, h = im.size
        glyphs.append((offset, w, h, advance, x_off, y_off, ch.replace("\\", "\\\\").replace("'", "\\'")))

    lines = [
        "// Scoreboard lettering from Staatliches (SIL Open Font License 1.1).",
        "// Generated by tools/fontconvert.py — do not edit by hand.",
        "#pragma once",
        "#include <lgfx/v1/lgfx_fonts.hpp>",
        "",
        "const uint8_t Scoreboard36pt7bBitmaps[] PROGMEM = {",
    ]
    row: list[str] = []
    for i, b in enumerate(bitmaps):
        row.append(f"0x{b:02X}")
        if len(row) == 12:
            lines.append("  " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("  " + ", ".join(row))
    lines.append("};")
    lines.append("")
    lines.append("const lgfx::GFXglyph Scoreboard36pt7bGlyphs[] PROGMEM = {")
    for i, (offset, w, h, adv, xo, yo, ch) in enumerate(glyphs):
        comma = "," if i + 1 < len(glyphs) else " "
        lines.append(
            f"  {{ {offset:5d}, {w:3d}, {h:3d}, {adv:3d}, {xo:4d}, {yo:4d} }}{comma} // 0x{FIRST+i:02X} '{ch}'"
        )
    lines.append("};")
    lines.append("")
    lines.append("const lgfx::GFXfont Scoreboard36pt7b PROGMEM = {")
    lines.append("  (uint8_t *)Scoreboard36pt7bBitmaps,")
    lines.append("  (lgfx::GFXglyph *)Scoreboard36pt7bGlyphs,")
    lines.append(f"  0x{FIRST:02X}, 0x{LAST:02X}, {y_advance} }};")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(bitmaps)} bitmap bytes, yAdvance={y_advance})")


if __name__ == "__main__":
    main()
