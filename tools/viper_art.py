from __future__ import annotations


def _pad24(lines: list[str]) -> list[str]:
    width = max(len(ln) for ln in lines)
    out = [ln.ljust(width) for ln in lines]
    if len(out) < 24:
        out.extend([" " * width] * (24 - len(out)))
    return out[:24]


